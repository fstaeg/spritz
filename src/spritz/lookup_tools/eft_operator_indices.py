# Naming:
#   "sm"              nominal point (column 0)
#   "wm1_<op>"        S - L_i + Q_i                       (Wilson coefficient -1)
#   "w1_<op>"         S + L_i + Q_i                       (+1)
#   "w11_<opi>_<opj>" S + L_i + L_j + Q_i + Q_j + M_ij    (both +1)

def get_group(dataset):
    ds = dataset.split("_")
    model, mllbin = None, None
    for i,substr in enumerate(ds):
        if substr.startswith("SMEFT"): 
            model = substr
        if substr.startswith("mll"): 
            mllbin = "_".join(ds[i:i+2])

    if model == "SMEFTsim":
        return "SMEFTsim"
    elif model == "SMEFTatNLO" and mllbin in group_a:
        return "SMEFTatNLO_group_a"
    elif model == "SMEFTatNLO" and mllbin in group_b:
        return "SMEFTatNLO_group_b"
    else:
        print(f"SMEFT dataset unknown: {dataset}")
        return

